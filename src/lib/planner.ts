import type { FoodItem, MealPlan, PlanMeal, Profile, Slot } from "../types"
import { F, care, mac, okf, today } from "./nutrition"

// slot, label, time, calorie share, protein share
const SL: [Slot, string, string, number, number][] = [
  ["b", "Breakfast", "7:30 AM", 0.25, 0.22], ["m", "Mid-morning", "10:30 AM", 0.1, 0.08], ["l", "Lunch", "1:00 PM", 0.3, 0.3],
  ["a", "Afternoon", "4:30 PM", 0.1, 0.07], ["d", "Dinner", "8:00 PM", 0.25, 0.33],
]
type Part = { f: FoodItem; q: number }
function tune(c: Part[], tk: number, tp: number, sec: FoodItem | null) {
  const t = (k: "kcal" | "p") => c.reduce((a, x) => a + x.f[k] * x.q, 0)
  const pr = c[1]
  if (pr) while (t("p") < tp && pr.q < 3) pr.q += 0.5
  if (pr && sec && t("p") < tp * 0.9 && !c.some((x) => x.f === sec)) {
    const x = { f: sec, q: 1 }; c.push(x)
    while (t("p") < tp && x.q < 2) x.q += 0.5
  }
  const fl = c[0]; if (!fl) return
  while (t("kcal") < tk * 0.9 && fl.q < 3) fl.q += 0.5
  while (t("kcal") > tk * 1.1 && fl.q > 0.5) fl.q -= 0.5
}
const GP: Record<string, string> = {
  loss: "keeps you full on fibre and protein while staying inside your calorie target",
  muscle: "spreads protein through the day to support muscle gain",
  diab: "pairs carbohydrate with dal, vegetables or protein to keep blood sugar steadier",
  heart: "keeps sodium and fried food low for heart health",
  preg: "brings iron- and protein-rich local foods for pregnancy",
}
export const rationale = (m: PlanMeal, p: Profile) => {
  const g = p.goals[0] ?? (p.t.sugar ? "diab" : "")
  return `${Math.round(mac(m.ps).p)} g protein toward your ${p.t.prot} g daily target; ${GP[g] ?? "a balanced local meal toward your daily targets"}.`
}
export function buildPlan(p: Profile): MealPlan {
  const T = p.t, cr = care(p)
  const P = (ids: string[]) => ids.map((i) => F[i]).filter((f): f is FoodItem => !!f && okf(f, p) && !(cr && /salty|fried|street/.test(f.t)))
  const pk = (ids: string[], i: number) => { const a = P(ids); return a.length ? a[i % a.length] : null }
  const main = ["rui", "chicken", "tilapia", "egg", "katla", "beef", "omelet", "pangas"], plant = ["soy", "chola", "masoor"]
  const fr = T.sugar ? ["guava", "papaya"] : ["banana", "guava", "papaya", "mango"]
  const days: PlanMeal[][] = []
  for (let d = 0; d < 7; d++) {
    days.push(SL.map(([s, lab, time, kf, pf]) => {
      const o = s === "d" ? 3 : 0
      const pr = pk(main, d + o) ?? pk(plant, d + o), dal = pk(["masoor", "mug"], d), veg = pk(["palong", "lal", "lau", "mixveg", "begun"], d + o)
      let c: (FoodItem | null)[]
      if (s === "b") c = [pk(d % 3 === 2 ? ["chira", "ruti"] : ["ruti", "chira"], 0), pk(["egg", "omelet", "chola", "mug", "soy"], d) ?? dal, veg]
      else if (s === "m") c = [pk(fr, d), pk(["dahi", "peanut", "egg", "chola"], d)]
      else if (s === "l") c = [pk(d === 1 || d === 4 ? ["brice", "rice"] : ["rice"], 0), pr, dal, veg, pk(["salad"], 0)]
      else if (s === "a") c = [pk(d === 2 && !cr ? ["jhal"] : ["muri"], 0), pk(["chola", "egg", "peanut", "soy"], d)]
      else c = [pk(d % 2 ? ["ruti", "rice"] : ["rice"], 0), pr, veg, pk(["lal", "palong"], d + 1)]
      const uniq = c.filter((f): f is FoodItem => !!f).filter((f, i, a) => a.indexOf(f) === i)
      const parts: Part[] = uniq.map((f) => ({ f, q: 1 }))
      tune(parts, T.kcal * kf, T.prot * pf, pk(["chola", "mug", "dahi", "soy", "masoor"], d + 1))
      return { s, lab, time, ps: parts.map((x): [string, number] => [x.f.id, x.q]), done: false }
    }))
  }
  const cau = ["This is educational guidance, not a diagnosis or medical advice."]
  if (T.sugar) cau.push("Rice and sweets are kept moderate and paired with dal, vegetables or protein.")
  if (cr) cau.push("Achar, shutki, packet snacks and fried foods are left out to keep sodium and fat in check.")
  if (p.conds.includes("ckd")) cau.push("CKD needs individual limits for protein, potassium and phosphorus. Confirm this plan with your kidney team.")
  if (p.goals.includes("preg")) cau.push("Pregnancy needs clinician guidance. Confirm iron, folate and fish choices with your doctor.")
  return { start: today(), days, cau, by: "Generated by the EdiByte rules engine using only the food dataset" }
}
