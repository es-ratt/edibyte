export type TKey = keyof typeof T
const IDX: Record<Lang, 0 | 1 | 2> = { en: 0, bn: 1, bl: 2 }

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = T[key][IDX[lang]]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

/** Old saved 'bl' (Banglish UI) falls back to English. */
export const normalizeLang = (l: Lang): Lang => (l === 'bn' ? 'bn' : 'en')

/** UI language -> language code the API expects. */
export const apiLang = (lang: Lang) => (lang === 'bl' ? 'banglish' : lang)

/** Numbers in Bangla digits for the Bangla UI, ASCII otherwise. */
export function fmtNum(n: number, lang: Lang, maxFrac = 0): string {
  return n.toLocaleString(lang === 'bn' ? 'bn-BD' : 'en-US', { maximumFractionDigits: maxFrac })
}
